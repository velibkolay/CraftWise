local ns = LoadAddon()
it("formats copper", function()
	eq(ns.FormatMoney(123456, true), "12g 34s 56c")
	eq(ns.FormatMoney(2474, true), "24s 74c")
	eq(ns.FormatMoney(0, true), "0c")
	eq(ns.FormatMoney(-9, true), "-9c")
	eq(ns.FormatMoney(10000, true), "1g")
	eq(ns.FormatMoney(nil, true), "?")
	eq(ns.FormatMoney(94.6, true), "95c")
end)

it("formats coins in the coin colours, at most two units (#159)", function()
	local g, s, c = "|cffF2C14E", "|cffC3C9D2", "|cffDB8A5C"
	eq(ns.FormatCoins(124020), g .. "12g|r " .. s .. "40s|r", "copper cut, not rounded")
	eq(ns.FormatCoins(6620), s .. "66s|r " .. c .. "20c|r")
	eq(ns.FormatCoins(7), c .. "7c|r")
	eq(ns.FormatCoins(0), c .. "0c|r")
	eq(ns.FormatCoins(30005), g .. "3g|r", "a zero second unit is left out")
	eq(ns.FormatCoins(-250), "−" .. s .. "2s|r " .. c .. "50c|r")
	eq(ns.FormatCoins(nil), nil)
end)
