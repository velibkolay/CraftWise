-- Issue #143: the price site's recipe data (web/public/data/recipes.json) is written by tools/gen_site_recipes.lua
-- from the bundled data files. This spec fails when the data files change and the JSON wasn't regenerated
-- (`lua5.1 tools/gen_site_recipes.lua`).
local G = dofile("tools/gen_site_recipes.lua")

local function Read(path)
	local f = io.open(path, "rb")
	if not f then
		return nil
	end
	local text = f:read("*a")
	f:close()
	return text
end

it("#143: the committed recipes.json matches what the generator writes now", function()
	local saved = Read(G.OUT)
	assert(saved, G.OUT .. " missing: run lua5.1 tools/gen_site_recipes.lua")
	assert(saved == G.Build(""), G.OUT .. " is out of date: run lua5.1 tools/gen_site_recipes.lua")
end)

it("#143: recipes.json carries every source header and the data unchanged", function()
	local text = G.Build("")
	for _, needle in ipairs({
		'"Generated by tools/gen_recipes.py — do not edit."',
		"(https://github.com/cjber/skillup-forever, GPL-3.0-or-later).",
		"LibPeriodicTable-3.1 Tradeskill.Mat.BySource.Vendor @ 130c6a9f7367 (LGPL-2.1).",
		'"2149": [165,2302,1,2318,2,2320,1]', -- Recipes.lua: skill line, output, quantity, reagents
		'"818": [185,0,0,4470,1]', -- a spell that makes no item
		'"2406": [2158,65]', -- Sources.lua: [2158] = { skill = 65, item = 2406 }
		'"2320": 10', -- Vendor.lua: Coarse Thread
		'"7418": "Enchant Bracer - Inferior Stamina"',
	}) do
		assert(text:find(needle, 1, true), needle)
	end
	assert(not text:find("luacheck", 1, true) and not text:find("stylua", 1, true), "tooling markers left out")
end)

it("#143: the JSON writer sorts keys numerically and keeps fractions exact", function()
	eq(G.Encode({ [10] = 1, [2] = 2.5, [100] = { 1, 0.1 } }, 0, ""), '{"2":2.5,"10":1,"100":[1,0.1]}')
	eq(G.Encode({ a = 'q"\\\n' }, 0, ""), '{"a":"q\\"\\\\\\n"}')
	eq(G.Encode({}, 0, ""), "[]")
end)
