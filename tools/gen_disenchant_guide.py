#!/usr/bin/env python3
"""Writes CraftWise/Data/DisenchantGuide.lua from Disenchantry's DisenchantResults.lua (#190).

Usage: python3 tools/gen_disenchant_guide.py "<path>/Disenchantry/DisenchantResults.lua" > CraftWise/Data/DisenchantGuide.lua

Only the original-era (Classic) tables are taken: Forever uses the original item levels and materials
(Disenchantry's own `expansion = 0` on Forever). The Outland and Northrend tables, Disenchantry's Forever
estimates (`guess=true` in ForecastPolicy.lua) and its Forever weapon tweak are left out: this is the plain
Classic baseline, labelled "Classic table (guide)" wherever it is shown.
Disenchantry v1.2.5, MIT, Copyright (c) 2026 x_Raven_x, Copyright (c) 2026 Rakuga (Disenchant Helper).
Python 3.10+, stdlib only.
"""
import re
import sys

SOURCE = "Disenchantry v1.2.5 (CurseForge), DisenchantResults.lua"


def block(text, name):
    m = re.search(r"local %s = \{\n(.*?)\n\}" % name, text, re.S)
    if not m:
        sys.exit("table %s not found" % name)
    return m.group(1)


def rows(body):
    out = []
    for m in re.finditer(r"\{([^{}]*)\}", body):
        out.append([None if v.strip() == "nil" else int(v) for v in m.group(1).split(",") if v.strip()])
    return out


def ids(text, name):
    m = re.search(r"local %s = \{(.*?)\n\}" % name, text, re.S)
    return [int(x) for x in re.findall(r"\[(\d+)\]=true", m.group(1))]


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    uncommon = rows(block(text, "uncommon"))
    rare = rows(block(text, "rare"))
    epic_m = re.search(r"expansion == 0 and (\{\{40,45.*?\}\})\n", text)
    epic = rows(epic_m.group(1))
    excluded = ids(text, "noDisenchant") + ids(text, "foreverNoDisenchant")
    out = []
    w = out.append
    w("-- Classic disenchanting baseline, the guide behind CraftWise's disenchant values (#190): used only where no")
    w("-- measured samples exist, always labelled \"Classic table (guide)\".")
    w("-- Source: %s, MIT, Copyright (c) 2026 x_Raven_x" % SOURCE)
    w("-- (Copyright (c) 2026 Rakuga for the parts from Disenchant Helper), which cites the community Classic")
    w("-- disenchanting tables (https://warcraft.wiki.gg/wiki/Disenchanting_tables). Original item levels only.")
    w("-- Generated by tools/gen_disenchant_guide.py; do not edit by hand.")
    w("local _, ns = ...")
    w("ns.DisenchantGuide = {")
    w("\tsource = \"%s\"," % SOURCE)
    w("\t-- uncommon: { minLevel, maxLevel, dustID, essenceID, shardID|nil, armourDust %, armourEssence %,")
    w("\t--   weaponDust %, weaponEssence %, dustMin, dustMax, essenceMin, essenceMax }; the shard (when there is")
    w("\t--   one) is the rest of 100 % and always one.")
    w("\tuncommon = {")
    for r in uncommon:
        w("\t\t{ " + ", ".join("nil" if v is None else str(v) for v in r) + " },")
    w("\t},")
    w("\t-- rare: { minLevel, maxLevel, shardID, [second material 0.5 %] }: 100 % one shard, or 99.5 / 0.5 %.")
    w("\trare = {")
    for r in rare:
        w("\t\t{ " + ", ".join(str(v) for v in r) + " },")
    w("\t},")
    w("\t-- epic: { minLevel, maxLevel, materialID, minQuantity, maxQuantity }, 100 %.")
    w("\tepic = {")
    for r in epic:
        w("\t\t{ " + ", ".join(str(v) for v in r) + " },")
    w("\t},")
    w("\t-- Items that cannot be disenchanted although quality and class say so (enchanter wands).")
    w("\texcluded = {")
    for i in excluded:
        w("\t\t[%d] = true," % i)
    w("\t},")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
