#!/usr/bin/env python3
"""Generate CraftWise/Data/RecipeVendors.lua: which vendors sell a recipe, from What's Training?'s Forever tables (#302).

The vendor lists come from the installed What's Training? add-on (MIT License, Copyright (c) 2019, author Sveng),
its Crafting/Recipes/Camelot/<Profession>.lua files; they are read at generation time, never at run time (its
recipe tables live in its private add-on namespace and WT_API has no recipe functions). Zone names come from this
build's DB2 AreaTable via wago.tools, the same pinned client as the other Data/ files. NPC names, coordinates and
prices are in neither What's Training?'s tables nor the client's DB2 (the Creature table has no names), so there are
none here: only CraftWise's own merchant recorder knows them, and an unseen vendor shows as "NPC <id>".

Usage: python3 tools/gen_recipe_vendors.py <path to the What's Training? add-on folder> [--refresh | --offline]
  e.g. python3 tools/gen_recipe_vendors.py "C:/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/WhatsTraining"
Run it after gen_recipes.py (it keeps only recipes that exist in Recipes.lua). Downloads are cached in tools/.cache/.
"""

