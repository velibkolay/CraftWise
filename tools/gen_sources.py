#!/usr/bin/env python3
"""Generate the required skill and recipe item of item-taught recipes from the pinned Forever client (stdlib only).

Adapted from SkillUp Forever's RecipeScrolls logic (scroll_requirements in tools/gen_thresholds.py and its use in
tools/gen_recipes.py, https://github.com/cjber/skillup-forever, commit 593e0e9), GPL-3.0-or-later, by cjber.
CraftWise is GPL-3.0; see LICENSE.

Changes from upstream:
- Writes CraftWise/Data/Sources.lua as ns.SourceData[recipeSpellID] = { skill = ..., item = ... } (issue #11), not
  upstream's ns.RecipeScrolls = { item, skill }.
- Takes the recipe spells from CraftWise's Thresholds.lua, as gen_recipes.py does.
- Counts every recipe it leaves out and why, and prints each class, so nothing is dropped unreported.
- Reads the recipe's own profession from SkillLineAbility only to report items whose RequiredSkill is another
  profession; those rows are kept as the client has them.

Only DB2 fields go in: no vendor, drop, quest or trainer data and no estimates.

Usage: python3 tools/gen_sources.py [--refresh | --offline], after gen_thresholds.py (same BUILD).
"""

import argparse
import sys
import urllib.error
from collections import Counter, defaultdict

from gen_recipes import threshold_ids
from gen_thresholds import BUILD, DATA, ITEM_DEPRECATED, PRODUCT, ROOT, SOURCE_DATE, UPSTREAM, db2, write_lua

OUTPUT = DATA / "Sources.lua"


def scroll_requirements(ids, item_rows, item_effect_rows, effect_link_rows):
    """([spell] = (item, skill line, skill rank), skip counts) for the items that teach each recipe spell.

    The item's own profession requirement is the skill at which the recipe can first be learned. Where several
    items teach one spell, the lowest requirement is the earliest any of them can be learned (lowest item ID on
    a tie). A deprecated item (ITEM_DEPRECATED) teaches nobody, so it is left out. `skipped` counts the recipe
    spells that an item teaches but no item gave a usable requirement, by reason.
    """
    taught = {int(row["ID"]): int(row["SpellID"]) for row in item_effect_rows}
    requirements = {}
    deprecated = set()
    for row in item_rows:
        item = int(row["ID"])
        if int(row.get("Flags_0") or 0) & ITEM_DEPRECATED:
            deprecated.add(item)
        else:
            requirements[item] = (int(row["RequiredSkill"]), int(row["RequiredSkillRank"]))
    scrolls = {}
    seen = defaultdict(set)  # spell -> why each item that teaches it was unusable
    for row in effect_link_rows:
        spell = taught.get(int(row["ItemEffectID"]))
        if spell not in ids:
            continue
        item = int(row["ItemID"])
        if item in deprecated:
            seen[spell].add("deprecated item")
            continue
        required = requirements.get(item)
        if required is None:
            seen[spell].add("item not in ItemSparse")
            continue
        if required[0] == 0 or required[1] <= 0:
            seen[spell].add("no required skill")
            continue
        held = scrolls.get(spell)
        if held is None or required[1] < held[2] or (required[1] == held[2] and item < held[0]):
            scrolls[spell] = (item, required[0], required[1])
    # The earliest requirement is 1: the client's placeholder, so it gives no requirement for this recipe.
    for spell in [spell for spell, held in scrolls.items() if held[2] == 1]:
        del scrolls[spell]
        seen[spell].add("placeholder skill 1")
    skipped = Counter()
    for spell, reasons in seen.items():
        if spell not in scrolls:
            skipped[" + ".join(sorted(reasons))] += 1
    return scrolls, skipped, seen


def professions_of(ability_rows, skill_rows, ids):
    """[spell] = the SkillLine IDs of its SkillLineAbility rows, each followed up to its top profession line."""
    parent = {int(row["ID"]): int(row["ParentSkillLineID"]) for row in skill_rows}
    result = defaultdict(set)
    for row in ability_rows:
        spell = int(row["Spell"])
        if spell not in ids:
            continue
        line = int(row["SkillLine"])
        lines = {line}
        while parent.get(line):
            line = parent[line]
            lines.add(line)
        result[spell] |= lines
    return result


def render(scrolls):
    lines = [
        "-- Generated by tools/gen_sources.py; do not edit.",
        "-- Where item-taught recipes come from (issue #11, part 1): the recipe item that teaches the recipe and the",
        "-- skill that item requires, per recipe spell ID.",
        "-- Source: Forever client DB2 ItemSparse (ID, RequiredSkillRank), ItemEffect and ItemXItemEffect (which item",
        f"-- teaches which spell), {PRODUCT} {BUILD}, {SOURCE_DATE}, via wago.tools,",
        f"-- https://wago.tools/db2/ItemSparse/csv?build={BUILD}. Generator adapted from SkillUp Forever's RecipeScrolls",
        f"-- ({UPSTREAM}, GPL-3.0-or-later).",
        "-- Only these two fields, and only where the client has them. Recipes whose item has no usable required skill",
        "-- (none, or the placeholder 1), deprecated items, and trainer-taught recipes are absent: absent means the",
        "-- client gives no requirement, not that none exists. Where several items teach a recipe, the lowest",
        "-- requirement wins. A skill can sit above the recipe's yellow; it is what the client says.",
        "-- Vendors, drops, quests and trainer fees are not in this file; they have no DB2 source.",
        "---@type string, table",
        "local _, ns = ...",
        "",
        "-- [recipeSpellID] = { skill = required skill to learn, item = recipe item ID }",
        "-- stylua: ignore",
        "ns.SourceData = {",
    ]
    for spell, (item, _, rank) in sorted(scrolls.items()):
        lines.append(f"\t[{spell}] = {{ skill = {rank}, item = {item} }},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--refresh", action="store_true", help="redownload the pinned sources")
    mode.add_argument("--offline", action="store_true", help="use cached sources only")
    args = parser.parse_args()
    options = {"refresh": args.refresh, "offline": args.offline}
    ids = threshold_ids()
    scrolls, skipped, seen = scroll_requirements(
        ids,
        db2("ItemSparse", ("ID", "RequiredSkill", "RequiredSkillRank", "Flags_0"), **options),
        db2("ItemEffect", ("ID", "SpellID"), **options),
        db2("ItemXItemEffect", ("ItemID", "ItemEffectID"), **options),
    )
    if not scrolls:
        raise ValueError("No usable recipe items; leaving existing generated output untouched")
    taught = len(scrolls) + sum(skipped.values())
    print(f"{len(ids)} recipes in Thresholds.lua; {taught} are taught by at least one item")
    print(f"{len(scrolls)} emitted; {sum(skipped.values())} skipped:")
    for reason, count in sorted(skipped.items()):
        print(f"  {reason}: {count}")
    lines = professions_of(
        db2("SkillLineAbility", ("Spell", "SkillLine"), **options),
        db2("SkillLine", ("ID", "ParentSkillLineID"), **options),
        ids,
    )
    item_skill = {
        int(row["ID"]): int(row["RequiredSkill"])
        for row in db2("ItemSparse", ("ID", "RequiredSkill"), **options)
    }
    other = sorted(spell for spell, (item, _, _) in scrolls.items() if item_skill[item] not in lines[spell])
    print(f"{len(other)} emitted recipes whose item requires a skill line the recipe is not in: {other}")
    write_lua(OUTPUT, render(scrolls))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(scrolls)} recipe spell IDs")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, urllib.error.URLError) as error:
        sys.exit(f"error: {error}")
