-- Builds web/site/lib/enums.ts: item class, subclass and quality names for the price site (#97).
-- Source: Gethe/wow-ui-source, branch "forever", Interface/AddOns/Blizzard_APIDocumentationGenerated
-- (Enum.ItemClass, Enum.Item<Class>Subclass, Enum.ItemQuality). These are the client's enum identifiers, not
-- the localized names the game shows (GetItemClassInfo); classes without a subclass enum (Tradegoods,
-- Gem, ...) have no subclass names here.
-- Usage: lua5.1 tools/gen_item_enums.lua <wow-ui-source checkout> > web/site/lib/enums.ts
local root = assert(arg[1], "path to a wow-ui-source checkout (branch forever)")
local dir = root .. "/Interface/AddOns/Blizzard_APIDocumentationGenerated/"
local enums = {}
APIDocumentation = { AddDocumentationTable = function(_, t)
	for _, e in ipairs(t.Tables or {}) do
		if e.Type == "Enumeration" then
			enums[e.Name] = e.Fields
		end
	end
end }
local version = io.open(root .. "/version.txt"):read("*l")
for _, file in ipairs({ "ItemConstantsDocumentation.lua", "ItemQualitiesDocumentation.lua" }) do
	local chunk = assert(loadfile(dir .. file))
	local dummy
	dummy = setmetatable({}, { __index = function() return dummy end })
	setfenv(chunk, setmetatable({ APIDocumentation = APIDocumentation }, { __index = function(_, k)
		return _G[k] ~= nil and _G[k] or dummy
	end }))
	chunk()
end

local function sortedFields(fields)
	local list = {}
	for _, f in ipairs(fields) do list[#list + 1] = f end
	table.sort(list, function(a, b) return a.EnumValue < b.EnumValue end)
	return list
end

local function map(fields, indent)
	local out = {}
	for _, f in ipairs(sortedFields(fields)) do
		out[#out + 1] = string.format('%s%d: "%s",', indent, f.EnumValue, f.Name)
	end
	return table.concat(out, "\n")
end

local classes = assert(enums.ItemClass, "Enum.ItemClass not found")
local lines = {
	"// Generated by tools/gen_item_enums.lua from Blizzard's API docs for the Forever client (" .. version .. "); do not edit.",
	"// Enum identifiers (Enum.ItemClass, Enum.Item<Class>Subclass, Enum.ItemQuality), not the client's localized names.",
	"",
	"export const ITEM_CLASS: Record<number, string> = {",
	map(classes, "\t"),
	"};",
	"",
	"export const ITEM_SUBCLASS: Record<number, Record<number, string>> = {",
}
for _, c in ipairs(sortedFields(classes)) do
	local sub = enums["Item" .. c.Name .. "Subclass"]
	if sub then
		lines[#lines + 1] = string.format("\t%d: {", c.EnumValue)
		lines[#lines + 1] = map(sub, "\t\t")
		lines[#lines + 1] = "\t},"
	end
end
lines[#lines + 1] = "};"
lines[#lines + 1] = ""
lines[#lines + 1] = "export const ITEM_QUALITY: Record<number, string> = {"
lines[#lines + 1] = map(assert(enums.ItemQuality, "Enum.ItemQuality not found"), "\t")
lines[#lines + 1] = "};"
io.write(table.concat(lines, "\n"), "\n")
